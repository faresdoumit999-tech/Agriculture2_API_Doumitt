"""SQLAlchemy 2.0 ORM models for DOUMITT Agricultural ERP."""

from __future__ import annotations

from datetime import date, datetime, timezone

from sqlalchemy import Boolean, Date, DateTime, Float, ForeignKey, Integer, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from database import Base


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class User(Base):
    __tablename__ = "users"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    username: Mapped[str] = mapped_column(String(50), unique=True, index=True, nullable=False)
    phone_number: Mapped[str | None] = mapped_column(String(30), nullable=True)
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)
    role: Mapped[str] = mapped_column(String(20), default="user", server_default="user", nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utc_now, nullable=False
    )

    projects: Mapped[list[Project]] = relationship(
        back_populates="owner", cascade="all, delete-orphan"
    )
    warehouse_items: Mapped[list[WarehouseItem]] = relationship(
        back_populates="owner", cascade="all, delete-orphan"
    )
    expenses: Mapped[list[ExpenseRecord]] = relationship(
        back_populates="owner", cascade="all, delete-orphan"
    )
    invoices: Mapped[list[Invoice]] = relationship(
        back_populates="owner", cascade="all, delete-orphan"
    )


class Project(Base):
    """A season/project. Each project belongs to at most one sharecropper."""

    __tablename__ = "projects"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )
    name: Mapped[str] = mapped_column(String(150), nullable=False)
    greenhouse_count: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    crops_planted: Mapped[str | None] = mapped_column(String(500), nullable=True)
    season_start_date: Mapped[date] = mapped_column(Date, nullable=False)
    season_end_date: Mapped[date | None] = mapped_column(Date, nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    has_sharecropper: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    sharecropper_name: Mapped[str | None] = mapped_column(String(150), nullable=True)
    sharecropper_profit_pct: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    sharecropper_expense_pct: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    notes: Mapped[str | None] = mapped_column(String(1000), nullable=True)

    owner: Mapped[User] = relationship(back_populates="projects")
    expenses: Mapped[list[ExpenseRecord]] = relationship(
        back_populates="project", cascade="all, delete-orphan"
    )
    invoices: Mapped[list[Invoice]] = relationship(
        back_populates="project", cascade="all, delete-orphan"
    )


class WarehouseItem(Base):
    """A purchase from an agricultural pharmacy, consumed in decimal parts."""

    __tablename__ = "warehouse_items"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )
    product_name: Mapped[str] = mapped_column(String(200), index=True, nullable=False)
    pharmacy_name: Mapped[str] = mapped_column(String(200), index=True, nullable=False)
    purchase_date: Mapped[date] = mapped_column(Date, nullable=False)
    initial_quantity: Mapped[float] = mapped_column(Float, nullable=False)
    remaining_quantity: Mapped[float] = mapped_column(Float, nullable=False)
    unit: Mapped[str] = mapped_column(String(50), default="لتر/عبوة", nullable=False)
    currency: Mapped[str] = mapped_column(String(3), nullable=False)
    exchange_rate: Mapped[float] = mapped_column(Float, default=1.0, nullable=False)
    unit_price_usd: Mapped[float] = mapped_column(Float, nullable=False)
    unit_price_syp: Mapped[float] = mapped_column(Float, nullable=False)
    total_cost_usd: Mapped[float] = mapped_column(Float, nullable=False)
    total_cost_syp: Mapped[float] = mapped_column(Float, nullable=False)

    owner: Mapped[User] = relationship(back_populates="warehouse_items")
    expenses: Mapped[list[ExpenseRecord]] = relationship(back_populates="warehouse_item")


class ExpenseRecord(Base):
    """Seasonal or daily expense, optionally generated by a warehouse withdrawal."""

    __tablename__ = "expenses"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )
    project_id: Mapped[int] = mapped_column(
        ForeignKey("projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    warehouse_item_id: Mapped[int | None] = mapped_column(
        ForeignKey("warehouse_items.id", ondelete="SET NULL"), nullable=True
    )
    date: Mapped[date] = mapped_column(Date, index=True, nullable=False)
    expense_nature: Mapped[str] = mapped_column(String(20), index=True, nullable=False)
    category: Mapped[str] = mapped_column(String(30), index=True, nullable=False)
    item_name: Mapped[str] = mapped_column(String(200), nullable=False)
    pharmacy_name: Mapped[str | None] = mapped_column(String(200), index=True, nullable=True)
    quantity_used: Mapped[float] = mapped_column(Float, default=1.0, nullable=False)
    unit_price: Mapped[float] = mapped_column(Float, nullable=False)
    currency: Mapped[str] = mapped_column(String(3), nullable=False)
    exchange_rate: Mapped[float] = mapped_column(Float, default=1.0, nullable=False)
    total_amount_usd: Mapped[float] = mapped_column(Float, nullable=False)
    total_amount_syp: Mapped[float] = mapped_column(Float, nullable=False)
    enters_sharecropper_calc: Mapped[bool] = mapped_column(
        Boolean, default=False, nullable=False
    )
    custom_sharecropper_pct: Mapped[float | None] = mapped_column(Float, nullable=True)
    sharecropper_deduction_usd: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_deduction_syp: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )

    owner: Mapped[User] = relationship(back_populates="expenses")
    project: Mapped[Project] = relationship(back_populates="expenses")
    warehouse_item: Mapped[WarehouseItem | None] = relationship(back_populates="expenses")


class Invoice(Base):
    """Vegetable-market invoice with the complete sharecropper settlement."""

    __tablename__ = "invoices"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )
    project_id: Mapped[int] = mapped_column(
        ForeignKey("projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    date: Mapped[date] = mapped_column(Date, index=True, nullable=False)
    currency: Mapped[str] = mapped_column(String(3), default="SYP", nullable=False)
    exchange_rate: Mapped[float] = mapped_column(Float, default=1.0, nullable=False)
    total_gross: Mapped[float] = mapped_column(Float, nullable=False)
    commission_amount: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    polystyrene_expense: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    vehicle_fuel_expense: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    other_deductions: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    net_total: Mapped[float] = mapped_column(Float, nullable=False)
    net_total_usd: Mapped[float] = mapped_column(Float, nullable=False)
    net_total_syp: Mapped[float] = mapped_column(Float, nullable=False)
    sharecropper_applied_profit_pct: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_applied_expense_pct: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_gross_share_syp: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_expense_deduction_syp: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_net_payout_syp: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    sharecropper_net_payout_usd: Mapped[float] = mapped_column(
        Float, default=0.0, nullable=False
    )
    owner_net_profit_syp: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    owner_net_profit_usd: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)

    owner: Mapped[User] = relationship(back_populates="invoices")
    project: Mapped[Project] = relationship(back_populates="invoices")
    items: Mapped[list[InvoiceItem]] = relationship(
        back_populates="invoice", cascade="all, delete-orphan"
    )


class InvoiceItem(Base):
    __tablename__ = "invoice_items"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    invoice_id: Mapped[int] = mapped_column(
        ForeignKey("invoices.id", ondelete="CASCADE"), index=True, nullable=False
    )
    crop_name: Mapped[str] = mapped_column(String(150), index=True, nullable=False)
    box_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    gross_weight: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    net_weight: Mapped[float] = mapped_column(Float, nullable=False)
    unit_price: Mapped[float] = mapped_column(Float, nullable=False)
    subtotal: Mapped[float] = mapped_column(Float, nullable=False)

    invoice: Mapped[Invoice] = relationship(back_populates="items")
